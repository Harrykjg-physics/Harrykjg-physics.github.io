/* ---- render the list into #physicists-content ---- */
(function () {
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  function render() {
    var el = document.getElementById("physicists-content");
    if (!el) return;
    var list = window.PHYSICISTS || [];
    /* Layout: aim for ~10 entries per column, but cap the number of
       columns so the list never overflows the page width.
       Adjust MAX_COLS / PER_COL here if you like. */
    var MAX_COLS = 4;
    var PER_COL = 10;
    var cols = Math.min(Math.ceil(list.length / PER_COL), MAX_COLS) || 1;
    var rows = Math.ceil(list.length / cols);
    var html = '<div class="phys-multi" style="grid-template-rows: repeat(' + rows + ', auto);">';
    list.forEach(function (p) {
      html += '<div class="phys-item">';
      html += '<strong>' + esc(p.name) + '</strong>';
      if (p.affiliation) html += ' <span class="muted">— ' + esc(p.affiliation) + '</span>';
      var links = [];
      if (p.home) links.push('<a href="' + esc(p.home) + '" target="_blank" rel="noopener">Homepage</a>');
      if (p.scholar) links.push('<a href="' + esc(p.scholar) + '" target="_blank" rel="noopener">Google Scholar</a>');
      if (links.length) html += '<br>' + links.join(' &nbsp;&middot;&nbsp; ');
      html += '</div>';
    });
    html += '</div>';
    el.innerHTML = html;
  }

  render();
})();
